"""
ara_phase_trust_gate_diagnostic.py

Strict-causal diagnostic for the next hybrid question:

    lag ridge = carried energy / native-unit inertia
    ARA phase-flow = route / timing / turn geometry

The goal is not to average lag and ARA.  The goal is to ask:

  1. When lag and ARA phase-flow disagree, which channel is more often right
     about direction/turn?
  2. Can ARA disagreement act as a warning that lag is entering a risky
     boundary/turn window?
  3. Does a simple causal trust selector help, using only past completed
     outcomes?

Leakage guard:

  - Base lag and phase-flow predictions are generated by the strict-causal
    functions from ara_lag_phase_hybrid_predictor.py.
  - At origin t, training pairs for base models obey s+h<t.
  - The trust selector for origin t only uses previous records whose
    target_anchor < t, so their outcomes would already be known.
"""

