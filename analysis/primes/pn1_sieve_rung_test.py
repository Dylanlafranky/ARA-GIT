def run_analysis(output_dir: Path | None = None) -> dict[str, object]:
    output_dir = Path(output_dir) if output_dir is not None else HERE
    output_dir.mkdir(parents=True, exist_ok=True)

    observed_protocol_hash = sha256_file(PROTOCOL_PATH)
    if observed_protocol_hash != PROTOCOL_SHA256:
        raise RuntimeError(
            f"Frozen protocol hash mismatch: {observed_protocol_hash} != {PROTOCOL_SHA256}"
        )

    wheels: dict[int, Wheel] = {}
    active_primes: list[int] = []
    for prime in PRIMES:
        active_primes.append(prime)
        wheels[prime] = generate_wheel(tuple(active_primes))

    wheel_rows = [
        {
            "max_prime": prime,
            "period": wheel.period,
            "slots": len(wheel.residues),
            "mean_gap": float(np.mean(wheel.gaps)),
            "max_gap": int(np.max(wheel.gaps)),
            "gap_sum": int(np.sum(wheel.gaps)),
        }
        for prime, wheel in wheels.items()
    ]

    calibration_rows: list[dict[str, object]] = []
    primary_rows: list[dict[str, object]] = []
    sensitivity_rows: list[dict[str, object]] = []
    split_rows: list[dict[str, object]] = []
    saved_arrays: dict[str, np.ndarray] = {}

    for transition_index, (parent_prime, child_prime) in enumerate(HOLDOUT_TRANSITIONS):
        parent = wheels[parent_prime]
        child = wheels[child_prime]
        calibration_rows.append(calibration_check(parent, child, child_prime))
        primary, sensitivity, splits, arrays = run_transition(
            parent,
            child,
            child_prime,
            seed=SEED + transition_index * 10000,
        )
        primary_rows.extend(primary)
        sensitivity_rows.extend(sensitivity)
        split_rows.extend(splits)
        saved_arrays.update(arrays)

    wheel_df = pd.DataFrame(wheel_rows)
    calibration_df = pd.DataFrame(calibration_rows)
    primary_df = pd.DataFrame(primary_rows)
    sensitivity_df = pd.DataFrame(sensitivity_rows)
    split_df = pd.DataFrame(split_rows)

    all_exact_checks_pass = bool(calibration_df["all_exact_checks_pass"].all())
    primary_pass_count = int(primary_df["passes_frozen_primary"].sum())
    primary_claim_pass = bool(primary_pass_count == len(primary_df) == 4)
    split_same_direction_count = int(split_df["passes_same_direction"].sum())
    coordinate_rival_max_abs_difference = float(
        primary_df["coordinate_rival_abs_difference"].dropna().max()
    )

    if not all_exact_checks_pass:
        rating = "INVALID IMPLEMENTATION"
    elif primary_claim_pass and split_same_direction_count == len(split_df):
        rating = "SUPPORTED [pre-registered, arithmetic, unreplicated]"
    else:
        rating = "NOT SUPPORTED"

    generated_at = datetime.now(timezone.utc).isoformat()
    results: dict[str, object] = {
        "test_id": "T227 / PN1/v1",
        "generated_at_utc": generated_at,
        "orientation": "up = larger primorial period / later sieve rung",
        "protocol_path": str(PROTOCOL_PATH.relative_to(HERE.parents[1])).replace("\\", "/"),
        "protocol_sha256_expected": PROTOCOL_SHA256,
        "protocol_sha256_observed": observed_protocol_hash,
        "seed": SEED,
        "n_shuffles": N_SHUFFLES,
        "holdout_transitions": [f"{a}->{b}" for a, b in HOLDOUT_TRANSITIONS],
        "wheel_inventory": wheel_rows,
        "calibration": calibration_rows,
        "primary": primary_rows,
        "sensitivity": sensitivity_rows,
        "split_half": split_rows,
        "summary": {
            "all_exact_checks_pass": all_exact_checks_pass,
            "primary_comparisons_passed": primary_pass_count,
            "primary_comparisons_total": len(primary_df),
            "primary_claim_pass": primary_claim_pass,
            "split_half_checks_passed": split_same_direction_count,
            "split_half_checks_total": len(split_df),
            "coordinate_rival_max_abs_jsd_difference": coordinate_rival_max_abs_difference,
            "rating": rating,
            "evidence_ceiling": (
                "Finite deterministic arithmetic relation; exact checks are reconstruction. "
                "No Riemann-Hypothesis or physical-universality inference."
            ),
        },
        "environment": {
            "python": sys.version,
            "platform": platform.platform(),
            "numpy": np.__version__,
            "pandas": pd.__version__,
        },
    }

    wheel_df.to_csv(output_dir / "PN1_WHEEL_INVENTORY.csv", index=False)
    calibration_df.to_csv(output_dir / "PN1_CALIBRATION_CHECKS.csv", index=False)
    primary_df.to_csv(output_dir / "PN1_PRIMARY_DISTANCES.csv", index=False)
    sensitivity_df.to_csv(output_dir / "PN1_BIN_SENSITIVITY.csv", index=False)
    split_df.to_csv(output_dir / "PN1_SPLIT_HALF_CHECKS.csv", index=False)
    np.savez_compressed(output_dir / "PN1_HISTOGRAMS_AND_NULLS.npz", **saved_arrays)
    with (output_dir / "PN1_SIEVE_RUNG_RESULTS.json").open("w", encoding="utf-8") as handle:
        json.dump(results, handle, indent=2, allow_nan=False)

