    print(f"  shuffles: {N_SHUFFLES}")
    print(f"  exact checks: {all_exact_checks_pass}")
    print(f"  primary: {primary_pass_count}/{len(primary_df)}")
    print(f"  split halves: {split_same_direction_count}/{len(split_df)}")
    print(f"  rating: {rating}")
    print(primary_df.to_string(index=False))
