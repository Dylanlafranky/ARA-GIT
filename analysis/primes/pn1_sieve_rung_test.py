@dataclass(frozen=True)
class Wheel:
    max_prime: int
    period: int
    residues: np.ndarray
    gaps: np.ndarray


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest().upper()


def generate_wheel(primes: tuple[int, ...]) -> Wheel:
    """Generate the exact reduced residue wheel modulo the primorial."""
    period = math.prod(primes)
    admissible = np.ones(period, dtype=bool)
    for prime in primes:
        admissible[::prime] = False
    residues = np.flatnonzero(admissible).astype(np.int64)
    wrapped = np.concatenate((residues, residues[:1] + period))
    gaps = np.diff(wrapped).astype(np.int32)
    if int(gaps.sum()) != period:
        raise AssertionError("Circular gaps do not close to the primorial period")
    expected_phi = math.prod(prime - 1 for prime in primes)
    if len(residues) != expected_phi:
        raise AssertionError("Reduced residue count does not match Euler totient")
    return Wheel(primes[-1], period, residues, gaps)


def pair_coordinate(gaps: np.ndarray) -> np.ndarray:
    left = gaps.astype(np.float64, copy=False)
    right = np.roll(left, -1)
    return 2.0 * right / (left + right)


def pair_histogram(gaps: np.ndarray, bins: int, mask: np.ndarray | None = None) -> np.ndarray:
    values = pair_coordinate(gaps)
    if mask is not None:
        values = values[mask]
    counts, _ = np.histogram(values, bins=np.linspace(0.0, 2.0, bins + 1))
    probabilities = counts.astype(np.float64)
    probabilities /= probabilities.sum()
    return probabilities


def triple_histogram(gaps: np.ndarray, bins: int, mask: np.ndarray | None = None) -> np.ndarray:
    first = pair_coordinate(gaps)
    second = np.roll(first, -1)
    if mask is not None:
        first = first[mask]
        second = second[mask]
    counts, _, _ = np.histogram2d(
        first,
        second,
        bins=(np.linspace(0.0, 2.0, bins + 1), np.linspace(0.0, 2.0, bins + 1)),
    )
    probabilities = counts.astype(np.float64).ravel()
    probabilities /= probabilities.sum()
    return probabilities


def js_divergence_bits(p: np.ndarray, q: np.ndarray) -> float:
    """Jensen-Shannon divergence in bits, bounded from zero to one."""
    p = np.asarray(p, dtype=np.float64)
    q = np.asarray(q, dtype=np.float64)
    p = p / p.sum()
    q = q / q.sum()
    midpoint = 0.5 * (p + q)

    def kl_term(a: np.ndarray, b: np.ndarray) -> float:
        active = a > 0
        return float(np.sum(a[active] * np.log2(a[active] / b[active])))

    return 0.5 * kl_term(p, midpoint) + 0.5 * kl_term(q, midpoint)


def semicircle_mask_from_residues(residues: np.ndarray, period: int, half: int) -> np.ndarray:
    if half == 0:
        return residues < period / 2
    return residues >= period / 2


def shuffled_residue_positions(gaps: np.ndarray, first_residue: int, period: int) -> np.ndarray:
    positions = first_residue + np.concatenate(([0], np.cumsum(gaps[:-1], dtype=np.int64)))
    return np.mod(positions, period)


def calibration_check(parent: Wheel, child: Wheel, next_prime: int) -> dict[str, object]:
    lifts = parent.residues[:, None] + parent.period * np.arange(next_prime, dtype=np.int64)[None, :]
    release_matrix = np.mod(lifts, next_prime) == 0
    lifted_flat = lifts.ravel()
    release_flat = release_matrix.ravel()
    survivors = np.sort(lifted_flat[~release_flat])
    shed = np.sort(lifted_flat[release_flat])
    reconstructed = np.sort(np.concatenate((survivors, shed)))

    release_count_exact = int(release_flat.sum()) == len(parent.residues)
    release_fraction = float(release_flat.mean())
    expected_release_fraction = 1.0 / next_prime
    disjoint = np.intersect1d(survivors, shed, assume_unique=True).size == 0
    reconstructs_lift = np.array_equal(reconstructed, np.sort(lifted_flat))
    survivors_match_child = np.array_equal(survivors, child.residues)
    phase_exact = bool(np.array_equal(release_flat, np.mod(lifted_flat, next_prime) == 0))

    # Each parent-local geometry context is repeated q times. Because gcd(P_k,q)=1,
    # the q lifts visit every modular phase once, so every context has one release.
    row_release_counts = release_matrix.sum(axis=1)
    geometry_context_exactly_one_release = bool(np.all(row_release_counts == 1))
    geometry_conditional_max_error = float(
        np.max(np.abs(row_release_counts / next_prime - expected_release_fraction))
    )
    geometry_mutual_information_bits = 0.0 if geometry_conditional_max_error == 0.0 else float("nan")

    return {
        "transition": f"{parent.max_prime}->{next_prime}",
        "parent_period": parent.period,
        "child_period": child.period,
        "parent_slots": len(parent.residues),
        "lifted_slots": len(lifted_flat),
        "survivor_slots": len(survivors),
        "shed_slots": len(shed),
        "release_fraction_measured": release_fraction,
        "release_fraction_exact": expected_release_fraction,
        "release_count_exact": release_count_exact,
        "survivor_shed_disjoint": bool(disjoint),
        "reconstructs_lifted_parent": bool(reconstructs_lift),
        "survivors_match_child": bool(survivors_match_child),
        "phase_rule_exact": phase_exact,
        "geometry_context_exactly_one_release": geometry_context_exactly_one_release,
        "geometry_conditional_max_error": geometry_conditional_max_error,
        "geometry_mutual_information_bits": geometry_mutual_information_bits,
        "all_exact_checks_pass": bool(
            release_count_exact
            and disjoint
            and reconstructs_lift
            and survivors_match_child
            and phase_exact
            and geometry_context_exactly_one_release
            and geometry_conditional_max_error == 0.0
        ),
    }


def run_transition(
    parent: Wheel,
    child: Wheel,
    next_prime: int,
    seed: int,
) -> tuple[list[dict[str, object]], list[dict[str, object]], list[dict[str, object]], dict[str, np.ndarray]]:
    rng = np.random.default_rng(seed)

    pair_child = {
        bins: pair_histogram(child.gaps, bins) for bins in PAIR_BINS_SENSITIVITY
    }
    triple_child = {
        bins: triple_histogram(child.gaps, bins) for bins in TRIPLE_BINS_SENSITIVITY
    }
    pair_parent = {
        bins: pair_histogram(parent.gaps, bins) for bins in PAIR_BINS_SENSITIVITY
    }
    triple_parent = {
        bins: triple_histogram(parent.gaps, bins) for bins in TRIPLE_BINS_SENSITIVITY
    }

    pair_ordered = {
        bins: js_divergence_bits(pair_parent[bins], pair_child[bins])
        for bins in PAIR_BINS_SENSITIVITY
    }
    triple_ordered = {
        bins: js_divergence_bits(triple_parent[bins], triple_child[bins])
        for bins in TRIPLE_BINS_SENSITIVITY
    }

    pair_shuffle_distances = {
        bins: np.empty(N_SHUFFLES, dtype=np.float64) for bins in PAIR_BINS_SENSITIVITY
    }
    triple_shuffle_distances = {
        bins: np.empty(N_SHUFFLES, dtype=np.float64) for bins in TRIPLE_BINS_SENSITIVITY
    }
    pair_shuffle_hist_sum = np.zeros_like(pair_parent[PAIR_BINS_PRIMARY])

    split_results: dict[tuple[str, int], dict[str, object]] = {}
    for half in (0, 1):
        parent_mask = semicircle_mask_from_residues(parent.residues, parent.period, half)
        child_mask = semicircle_mask_from_residues(child.residues, child.period, half)
        split_results[("pair", half)] = {
            "ordered": js_divergence_bits(
                pair_histogram(parent.gaps, PAIR_BINS_PRIMARY, parent_mask),
                pair_histogram(child.gaps, PAIR_BINS_PRIMARY, child_mask),
            ),
            "shuffle": np.empty(N_SHUFFLES, dtype=np.float64),
        }
        split_results[("triple", half)] = {
            "ordered": js_divergence_bits(
                triple_histogram(parent.gaps, TRIPLE_BINS_PRIMARY, parent_mask),
                triple_histogram(child.gaps, TRIPLE_BINS_PRIMARY, child_mask),
            ),
            "shuffle": np.empty(N_SHUFFLES, dtype=np.float64),
        }

    child_half_pair = {
        half: pair_histogram(
            child.gaps,
            PAIR_BINS_PRIMARY,
            semicircle_mask_from_residues(child.residues, child.period, half),
        )
        for half in (0, 1)
    }
    child_half_triple = {
        half: triple_histogram(
            child.gaps,
            TRIPLE_BINS_PRIMARY,
            semicircle_mask_from_residues(child.residues, child.period, half),
        )
        for half in (0, 1)
    }

    for shuffle_index in range(N_SHUFFLES):
        shuffled = rng.permutation(parent.gaps)
        for bins in PAIR_BINS_SENSITIVITY:
            histogram = pair_histogram(shuffled, bins)
            pair_shuffle_distances[bins][shuffle_index] = js_divergence_bits(
                histogram, pair_child[bins]
            )
            if bins == PAIR_BINS_PRIMARY:
                pair_shuffle_hist_sum += histogram
        for bins in TRIPLE_BINS_SENSITIVITY:
            histogram = triple_histogram(shuffled, bins)
            triple_shuffle_distances[bins][shuffle_index] = js_divergence_bits(
                histogram, triple_child[bins]
            )

        shuffled_positions = shuffled_residue_positions(
            shuffled, int(parent.residues[0]), parent.period
        )
        for half in (0, 1):
            shuffled_mask = semicircle_mask_from_residues(
                shuffled_positions, parent.period, half
            )
            split_results[("pair", half)]["shuffle"][shuffle_index] = js_divergence_bits(
                pair_histogram(shuffled, PAIR_BINS_PRIMARY, shuffled_mask),
                child_half_pair[half],
            )
            split_results[("triple", half)]["shuffle"][shuffle_index] = js_divergence_bits(
                triple_histogram(shuffled, TRIPLE_BINS_PRIMARY, shuffled_mask),
                child_half_triple[half],
            )

    primary_rows: list[dict[str, object]] = []
    sensitivity_rows: list[dict[str, object]] = []

    def summarize(
        observable: str,
        bins: int,
        ordered: float,
        shuffled_distances: np.ndarray,
        primary: bool,
    ) -> dict[str, object]:
        p_value = (1 + int(np.sum(shuffled_distances <= ordered))) / (N_SHUFFLES + 1)
        row = {
            "transition": f"{parent.max_prime}->{next_prime}",
            "observable": observable,
            "bins": bins,
            "parent_slots": len(parent.gaps),
            "child_slots": len(child.gaps),
            "ordered_jsd_bits": ordered,
            "shuffle_median_jsd_bits": float(np.median(shuffled_distances)),
            "shuffle_q05_jsd_bits": float(np.quantile(shuffled_distances, 0.05)),
            "shuffle_q95_jsd_bits": float(np.quantile(shuffled_distances, 0.95)),
            "permutation_p_one_sided": p_value,
            "ordered_beats_shuffle_median": bool(ordered < np.median(shuffled_distances)),
            "passes_frozen_primary": bool(
                ordered < np.median(shuffled_distances) and p_value <= 0.05
            ) if primary else None,
        }
        return row

    for bins in PAIR_BINS_SENSITIVITY:
        row = summarize(
            "pair_x",
            bins,
            pair_ordered[bins],
            pair_shuffle_distances[bins],
            bins == PAIR_BINS_PRIMARY,
        )
        (primary_rows if bins == PAIR_BINS_PRIMARY else sensitivity_rows).append(row)
    for bins in TRIPLE_BINS_SENSITIVITY:
        row = summarize(
            "triple_xx",
            bins,
            triple_ordered[bins],
            triple_shuffle_distances[bins],
            bins == TRIPLE_BINS_PRIMARY,
        )
        (primary_rows if bins == TRIPLE_BINS_PRIMARY else sensitivity_rows).append(row)

    split_rows: list[dict[str, object]] = []
    for (observable, half), values in split_results.items():
        shuffled_distances = values["shuffle"]
        ordered = float(values["ordered"])
        p_value = (1 + int(np.sum(shuffled_distances <= ordered))) / (N_SHUFFLES + 1)
        split_rows.append(
            {
                "transition": f"{parent.max_prime}->{next_prime}",
                "observable": observable,
                "half": half + 1,
                "ordered_jsd_bits": ordered,
                "shuffle_median_jsd_bits": float(np.median(shuffled_distances)),
                "permutation_p_one_sided": p_value,
                "passes_same_direction": bool(
                    ordered < np.median(shuffled_distances) and p_value <= 0.05
                ),
            }
        )

    # Coordinate-rival audit. Transforming the registered x-bin edges into
    # log-ratio edges must produce the same counts because the map is monotone.
    x_edges = np.linspace(0.0, 2.0, PAIR_BINS_PRIMARY + 1)
    log_edges = np.empty_like(x_edges)
    log_edges[0] = -np.inf
    log_edges[-1] = np.inf
    interior = x_edges[1:-1]
    log_edges[1:-1] = np.log(interior / (2.0 - interior))

    def log_ratio_hist(gaps: np.ndarray) -> np.ndarray:
        values = np.log(np.roll(gaps.astype(np.float64), -1) / gaps)
        counts, _ = np.histogram(values, bins=log_edges)
        result = counts.astype(np.float64)
        return result / result.sum()

    log_parent = log_ratio_hist(parent.gaps)
    log_child = log_ratio_hist(child.gaps)
    coordinate_rival_jsd = js_divergence_bits(log_parent, log_child)
    coordinate_rival_abs_difference = abs(
        coordinate_rival_jsd - pair_ordered[PAIR_BINS_PRIMARY]
    )

    arrays = {
        f"{parent.max_prime}_{next_prime}_pair_parent": pair_parent[PAIR_BINS_PRIMARY],
        f"{parent.max_prime}_{next_prime}_pair_child": pair_child[PAIR_BINS_PRIMARY],
        f"{parent.max_prime}_{next_prime}_pair_shuffle_mean": pair_shuffle_hist_sum / N_SHUFFLES,
        f"{parent.max_prime}_{next_prime}_pair_shuffle_distances": pair_shuffle_distances[PAIR_BINS_PRIMARY],
        f"{parent.max_prime}_{next_prime}_triple_parent": triple_parent[TRIPLE_BINS_PRIMARY],
        f"{parent.max_prime}_{next_prime}_triple_child": triple_child[TRIPLE_BINS_PRIMARY],
        f"{parent.max_prime}_{next_prime}_triple_shuffle_distances": triple_shuffle_distances[TRIPLE_BINS_PRIMARY],
    }
    for row in primary_rows:
        row["coordinate_rival_log_ratio_jsd_bits"] = (
            coordinate_rival_jsd if row["observable"] == "pair_x" else None
        )
        row["coordinate_rival_abs_difference"] = (
            coordinate_rival_abs_difference if row["observable"] == "pair_x" else None
        )

    return primary_rows, sensitivity_rows, split_rows, arrays


